"""Generate src/vdi/font4x8.c -- a 4x8 system font for the ANTIC device.

WHY A FOUR-PIXEL CELL, and not a smaller version of the 8x8 face.

Every GEM resource is authored in CHARACTER CELLS, and gem4xe's are
authored for an EIGHTY column screen: the desktop's menu tree (ADMENU)
is 80 cells wide, and on the VBXE device 80 x 8 is exactly the 640-pixel
screen.  On a 320-pixel ANTIC screen the only cell width that reproduces
that is FOUR -- 320 / 4 = 80 -- so the menu bar is the width of the
screen and every dialog lands where it was drawn.  A 6x6 face would give
53 columns and the menu bar would run off the right-hand edge.

This is the trick the Atari 8-bit world used for 80-column text in
GRAPHICS 8 for the same reason: the screen is 320 pixels and 80 columns
is what people wanted.

THE GLYPHS ARE DRAWN HERE AS ART, not as hex, so that they can be read
and argued with.  Three pixels of ink and one of spacing; caps and
digits occupy rows 0-5, lowercase x-height rows 2-5, descenders reach
row 7.  The baseline is row 6 (FONT_TOP), which is the 8x8 face's too,
so the two fonts share every metric but width.

The strip's LAYOUT is unchanged from the 8x8 face (tools/fontconv.py):
256 bytes a row, eight rows, character N's byte on row r at
r * 256 + N.  A 4-wide glyph simply lives in the TOP NIBBLE of its byte,
which is what makes the device's glyph blit the same code for both.
"""

FONT_H, FONT_W, N = 8, 4, 256


def glyph_bytes(art):
    """Eight bytes, the glyph in each one's TOP nibble."""
    rows = art.split("/")
    if len(rows) != FONT_H:
        raise ValueError(f"{art!r}: {len(rows)} rows, expected {FONT_H}")
    out = []
    for r in rows:
        if len(r) != FONT_W:
            raise ValueError(f"{art!r}: row {r!r} is {len(r)} wide")
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= 0x80 >> i
        out.append(b)
    return out


def build():
    """The strip: 256 bytes a row, eight rows, char N at r*256 + N."""
    strip = [[0] * N for _ in range(FONT_H)]
    for ch, art in G.items():
        code = ord(ch)
        for r, b in enumerate(glyph_bytes(art)):
            strip[r][code] = b
    return strip


def main(path):
    strip = build()
    with open(path, "w") as f:
        f.write('/* Generated by tools/font4x8.py -- do not edit.\n'
                ' *\n'
                ' * A 4x8 system font for the ANTIC device: 320 / 4 is the\n'
                ' * eighty columns every GEM resource is authored for.  The\n'
                ' * layout is the 8x8 strip\'s -- 256 bytes a row, eight rows,\n'
                ' * character N\'s byte on row r at r*256 + N -- with each\n'
                ' * glyph in the TOP nibble of its byte.\n'
                ' */\n#include "vdi.h"\n\n'
                'const uint8_t __far font4x8[%d] = {\n' % (N * FONT_H))
        for r in range(FONT_H):
            f.write("    /* row %d */\n" % r)
            for i in range(0, N, 16):
                f.write("    " + " ".join("0x%02X," % b
                                          for b in strip[r][i:i + 16]) + "\n")
        f.write("};\n")
    print(f"{path}: {N * FONT_H} bytes, {len(G)} glyphs drawn")


